const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const { createHash } = require('node:crypto');
const { rawCid } = require('../component1-evaluation/statistics');
const ROOT = path.resolve(__dirname, '../..');
const RUNTIME = path.join(__dirname, '.runtime');
const RPC = 'http://127.0.0.1:8545';
const MARKER = '# Generated by Component 1 Phase 7 local setup';
const blockchainRequire = createRequire(path.join(ROOT, 'blockchain/package.json'));
function assertLocalSettings(env, kind) {
  const { isAddress, ZeroAddress } = blockchainRequire('ethers');
  const contractAddress = kind === 'backend' ? env.MEDICINE_TRACEABILITY_ADDRESS : env.VITE_TRACEABILITY_ADDRESS;
  if (!isAddress(contractAddress || '') || contractAddress.toLowerCase() === ZeroAddress || !env.IPFS_API_TOKEN || env.IPFS_API_TOKEN.length < 32) throw new Error('Invalid managed local address or operator configuration.');
  if (kind === 'backend') {
    if (env.WEB3_RPC_URL !== RPC || env.TRACEABILITY_NETWORK !== 'localhost' || env.HOST !== '127.0.0.1' || env.PORT !== '5001' || env.IPFS_MOCK_ONLY !== 'true' || env.IPFS_PROVIDER !== 'mock' || env.IPFS_PROVIDER_TOKEN) throw new Error('Backend must use loopback RPC and mock-only document settings.');
  } else if (kind === 'frontend') {
    if (env.TRACEABILITY_RPC_URL !== RPC || !/^\d+$/.test(env.VITE_TRACEABILITY_START_BLOCK || '') || Object.keys(env).some(key => key.startsWith('VITE_') && !['VITE_TRACEABILITY_ADDRESS', 'VITE_TRACEABILITY_START_BLOCK'].includes(key))) throw new Error('Frontend must use loopback RPC and approved public settings only.');
  } else throw new Error('Unsupported local configuration kind.');
}
function runtime() { fs.mkdirSync(RUNTIME, { recursive: true }); }
function readConfig(file) {
  const text = fs.readFileSync(file, 'utf8');
  if (!text.startsWith(MARKER)) throw new Error('Refusing unmanaged local configuration. Preserve it and review setup manually.');
  return Object.fromEntries(text.split(/\r?\n/).filter(line => line && !line.startsWith('#')).map(line => { const index = line.indexOf('='); return [line.slice(0, index), line.slice(index + 1)]; }));
}
async function rpc(method, params = []) {
  const response = await fetch(RPC, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }), signal: AbortSignal.timeout(2000) });
  const result = await response.json(); if (!response.ok || result.error) throw new Error('Local RPC request failed.'); return result.result;
}
async function checkChain() {
  if (BigInt(await rpc('eth_chainId')) !== 31337n || !String(await rpc('web3_clientVersion')).toLowerCase().includes('hardhat')) throw new Error('Expected local Hardhat chain 31337.');
}
function loadHardhat() {
  process.env.HARDHAT_CONFIG = path.join(ROOT, 'blockchain/hardhat.config.js');
  process.env.HARDHAT_NETWORK = 'localhost';
  const hre = blockchainRequire('hardhat');
  const url = new URL(hre.network.config.url);
  if (hre.network.name !== 'localhost' || !['127.0.0.1', 'localhost'].includes(url.hostname) || url.port !== '8545' || url.username || url.password) throw new Error('Only the existing local RPC configuration is supported.');
  return hre;
}
function pdf(label) {
  const stream = `BT /F1 16 Tf 40 100 Td (SYNTHETIC PUBLIC ${label} - NO PATIENT DATA) Tj ET`;
  const objects = ['<< /Type /Catalog /Pages 2 0 R >>', '<< /Type /Pages /Kids [3 0 R] /Count 1 >>', '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 600 200] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>', '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>', `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`];
  let text = '%PDF-1.4\n'; const offsets = [];
  objects.forEach((object, index) => { offsets.push(Buffer.byteLength(text)); text += `${index + 1} 0 obj\n${object}\nendobj\n`; });
  const offset = Buffer.byteLength(text);
  text += `xref\n0 6\n0000000000 65535 f \n${offsets.map(value => String(value).padStart(10, '0') + ' 00000 n ').join('\n')}\ntrailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${offset}\n%%EOF\n`;
  return Buffer.from(text);
}
function fixtures() {
  return [['certificate.pdf', 'CERTIFICATE'], ['laboratory-report.pdf', 'LABORATORY REPORT']].map(([name, label]) => {
    const bytes = pdf(label); return { name, bytes, cid: rawCid(bytes), sha256: createHash('sha256').update(bytes).digest('hex') };
  });
}
